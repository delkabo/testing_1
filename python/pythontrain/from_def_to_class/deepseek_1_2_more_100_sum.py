"""
Задача 2: Сумма больше 100
Темы: Списки, Циклы, Условия

Вам дана строка с числами, разделенными запятыми. Необходимо найти все числа, которые больше 100, и вывести их сумму. Если таких чисел нет, выведите «0».

Формат ввода: Одна строка, содержащая целые числа, разделенные запятыми. Числа находятся в диапазоне от -1000 до 1000.

Формат вывода: Целое число — сумма всех чисел, больших 100.

Пример 1:
Входные данные: 50, 150, 200, 30, 101
Выходные данные: 451

Пример 2:
Входные данные: 10, 20, 30
Выходные данные: 0"""

def sum_more_100(give_data: str) -> str:
    give_data_split = give_data.split(',')
    more_100_sums = 0
    print(give_data_split)
    for x in give_data_split:
        if int(x) > 100:
            more_100_sums += int(x)
    
    return more_100_sums


# give_data = input()
give_data = "10, 20, 30"
get_answer = sum_more_100(give_data)
print(get_answer)