"""Задача 1: Четные и нечетные
Темы: Условные операторы, Циклы, Списки

На вход подается список целых чисел, разделенных пробелами. Ваша задача — определить, сколько чисел в этом списке являются четными, а сколько нечетными. Ноль считается четным числом.

Формат ввода: Одна строка, содержащая целые числа, разделенные пробелами. Длина списка не превышает 100 элементов.

Формат вывода: Одна строка в формате: «четных: A, нечетных: B», где A и B — количество четных и нечетных чисел соответственно.

Пример 1:
Входные данные: 1 2 3 4 5 6
Выходные данные: четных: 3, нечетных: 3

Пример 2:
Входные данные: 0 0 0 1 1
Выходные данные: четных: 3, нечетных: 2"""

def even_odds(numbers: str) -> str:
    split_num = numbers.split()
    even_num = 0
    odds_num = 0
    for x in split_num:
        if int(x) % 2 == 0 and int(x) != 0:
            even_num += 1
        elif int(x) % 2 != 0 and int(x) != 0:
            odds_num += 1

    return f"четных {even_num}, нечетных {odds_num}"

