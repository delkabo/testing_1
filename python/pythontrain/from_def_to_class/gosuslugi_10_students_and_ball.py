
'''
Темы: Списки, Словари, Циклы
В классе 5 студентов. На вход подается строка с их именами (разделены запятыми) и строка с их баллами (разделены запятыми) в том же порядке. 
Определите, кто из студентов получил балл выше среднего. Выведите имена таких студентов, каждое на новой строке, в исходном порядке.
Если таких нет, выведите «Нет».
Формат ввода: Две строки: первая — имена через запятую, вторая — баллы через запятую. Баллы — целые числа от 0 до 100.
Формат вывода: Имена студентов с баллами выше среднего, каждое на новой строке.

Пример 1:
Входные данные:
Анна, Борис, Вика, Глеб, Даша
85, 70, 95, 60, 80
Выходные данные:
Анна
Вика
Даша

Пример 2:
Входные данные:
Анна, Борис, Вика, Глеб, Даша
50, 50, 50, 50, 50
Выходные данные:'''

def get_students(students: str, ball: str) -> str:
    arr_stud = students.split(', ')
    arr_ball = ball.split(', ')
    summ_ball = 0
    average_ball = 0
    for count in arr_ball:
        summ_ball += int(count)

    average_ball = summ_ball / len(arr_ball)
    print(average_ball)

    for count in range(0, len(arr_ball)):
        if int(arr_ball[count]) > average_ball:
            print(f"{arr_stud[count]} ,балл: {arr_ball[count]}")


students = 'Анна, Борис, Вика, Глеб, Даша'
ball = '85, 70, 95, 60, 80'
getAnsw = get_students(students, ball)
